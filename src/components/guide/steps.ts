/**
 * Шаги путеводителя. Тексты не раскрывают сюжет: только то, что читатель знает с первой страницы.
 * Каждый шаг подсвечивает настоящие элементы интерфейса; первый из них — главный, к нему тянется нить от карточки.
 */
export interface GuideStep {
  id: string;
  /** Латинская рубрика, как у разделов атласа. */
  rubric: string;
  title: string;
  text: string;
  /** CSS-селекторы подсвечиваемых элементов (не больше трёх). */
  targets: string[];
  /** Шагу нужен план аббатства: путеводитель сам приводит туда читателя. */
  needsMap?: boolean;
  /** В карточке — настоящий выбор режима чтения. */
  picker?: boolean;
}

